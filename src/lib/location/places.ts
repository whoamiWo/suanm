/** 获取城市经度，未收录时回退到省级默认值 */
export function cityLongitude(cityCode: string, provinceCode?: string): number | undefined {
  const direct = CITY_LONGITUDE[cityCode];
  if (direct !== undefined) return direct;
  if (provinceCode) {
    const fallback = PROVINCE_LONGITUDE[provinceCode];
    if (fallback !== undefined) return fallback;
  }
  return CITY_LONGITUDE[provinceCode ?? ''];
}
